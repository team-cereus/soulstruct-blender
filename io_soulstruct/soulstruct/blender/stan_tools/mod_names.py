"""Display names for a mod's own characters (e.g. Nightreign Eclipse ports), read from the mod's files.

NpcParam rows `c####xxxx` belong to character `c####` and point at an NpcName text entry through `nameId`. The NpcParam
rows come from the mod's exported params (`nr_unpack.mod_params_dir`) and the names from the mod's
`msg/engus/item*.msgbnd.dcx` NpcName FMGs. Results are cached until either file changes.
"""
from __future__ import annotations

__all__ = ["mod_character_names", "eclipse_roster_names"]

import logging
import xml.etree.ElementTree as ET
from collections import Counter
from functools import lru_cache
from pathlib import Path

_LOGGER = logging.getLogger("soulstruct.blender.stan_tools")
_MSG_LANGUAGES = ("engus",)


def _mtime(path: Path) -> int:
    try:
        return path.stat().st_mtime_ns
    except OSError:
        return 0


@lru_cache(maxsize=4)
def _name_ids_by_chr(npc_param_xml: str, mtime_ns: int) -> dict[int, int]:
    """Character model -> NpcName id: the `c####0000` row's name, else the most common name among its rows."""
    del mtime_ns
    counts: dict[int, Counter] = {}
    base: dict[int, int] = {}
    for _event, row in ET.iterparse(npc_param_xml, events=("end",)):
        if row.tag != "row":
            continue
        try:
            row_id, name_id = int(row.attrib["id"]), int(row.attrib.get("nameId", "-1"))
        except (KeyError, ValueError):
            row.clear()
            continue
        row.clear()
        if row_id < 10000 or name_id <= 0:
            continue
        chr_id = row_id // 10000
        if row_id % 10000 == 0:
            base[chr_id] = name_id
        counts.setdefault(chr_id, Counter())[name_id] += 1
    return {chr_id: base.get(chr_id) or c.most_common(1)[0][0] for chr_id, c in counts.items()}


@lru_cache(maxsize=4)
def _npc_names(msgbnd_paths: tuple[str, ...], mtimes: tuple[int, ...]) -> dict[int, str]:
    del mtimes
    from soulstruct.base.text.fmg import FMG
    from soulstruct.containers import Binder

    names: dict[int, str] = {}
    for path in msgbnd_paths:  # later binders (DLC) win
        try:
            binder = Binder.from_path(path)
        except Exception as ex:  # unreadable (e.g. no Oodle DLL): just no mod names
            _LOGGER.warning(f"Could not read {path} for character names: {ex}")
            continue
        for entry in binder.entries:
            if not entry.name.lower().startswith("npcname"):
                continue
            try:
                fmg = FMG.from_binder_entry(entry)
            except Exception as ex:
                _LOGGER.warning(f"Could not read {entry.name} in {path}: {ex}")
                continue
            names.update({k: v for k, v in fmg.entries.items() if v and v.strip()})
    return names


@lru_cache(maxsize=1)
def eclipse_roster_names() -> dict[int, str]:
    """Bundled names of Nightreign Eclipse's ported characters (`general/character_names/eclipse.json`, generated by
    `tools/gen_eclipse_names.py` from the Eclipse port roster). Covers ports whose NpcParam rows have no name."""
    import json

    path = Path(__file__).resolve().parent.parent / "general" / "character_names" / "eclipse.json"
    try:
        return {int(k): v for k, v in json.loads(path.read_text(encoding="utf-8")).items()}
    except (OSError, ValueError):
        return {}


def mod_character_names(mod_root: Path, stan_settings) -> dict[int, str]:
    """Model number -> name for characters the mod names itself. Empty until the mod's params are exported."""
    from .nr_unpack import mod_params_dir

    reg_dir = mod_params_dir(mod_root)
    if reg_dir is None:
        return {}
    xml = reg_dir / "NpcParam.param.xml"
    msgbnds = tuple(
        str(p) for lang in _MSG_LANGUAGES
        for p in sorted((mod_root / "msg" / lang).glob("item*.msgbnd*"))
    )
    if not xml.is_file() or not msgbnds:
        return {}
    try:
        name_ids = _name_ids_by_chr(str(xml), _mtime(xml))
        texts = _npc_names(msgbnds, tuple(_mtime(Path(p)) for p in msgbnds))
    except Exception as ex:  # never break the character list
        _LOGGER.warning(f"Could not read mod character names: {ex}")
        return {}
    return {chr_id: texts[name_id].strip() for chr_id, name_id in name_ids.items() if name_id in texts}
